DECLARE @subtable TABLE(custid int)
DECLARE @ids varchar(max),  @running_cnt int

SELECT  @running_cnt = 0

WHILE (1 = 1)
BEGIN
	DELETE @subtable
	SELECT @ids = ''

	DELETE TOP (100) #temp
	OUTPUT deleted.custid
	INTO @subtable(custid)	

	IF @@ROWCOUNT = 0 BREAK
	
	SELECT @ids = STUFF((
		SELECT ',' + cast(custid as varchar(10)) 
		FROM @subtable 
		FOR XML PATH('')
	), 1,1,'')
	
	EXEC dbo.Acc_ExecRep_Cust_09 @ids = @ids
	
	IF @running_cnt = 30
	BEGIN
		WAITFOR DELAY '00:00:01'
		SET @running_cnt = 0
	END
	
	SET @running_cnt = @running_cnt + 1
END	


	
ALTER PROCEDURE [dbo].[Acc_ExecRep_Cust_09]
	@ids varchar(max)
AS
BEGIN
	SET NOCOUNT ON;
	
	IF (SELECT COUNT(1)
		FROM sys.objects
		WHERE NAME IN ('custinfo') AND type = 'U'
		) <> 1 RETURN 
	
	DECLARE @res AS TABLE (custid INT)
	DECLARE @splitter CHAR(1), @string VARCHAR(MAX)

	SELECT @splitter = ',', @string = @ids

	IF SUBSTRING (@string, LEN (@string), 1) <> @splitter
		  SET @string= @string+@splitter

	DECLARE @START INT, @word NVARCHAR(4000), @CHARINDEX INT, @i INT
	SET @i=1
	SET @START=1
	SET @CHARINDEX= CHARINDEX( @splitter, @string, @START)
	WHILE (@CHARINDEX <> 0)BEGIN
		SET @word= SUBSTRING( @string, @START, @CHARINDEX - @START)
		SET @START= @CHARINDEX +1
		SET @CHARINDEX= CHARINDEX( @splitter, @string, @START)
		INSERT INTO @res  VALUES(CAST(@word AS INT))
		SET @i=@i+1
	END

	 DECLARE @tmp_settings table(
		currency int,
		maxbet money,		
		maxperball money
	)

	INSERT INTO @tmp_settings(currency,maxbet,maxperball)
			  SELECT 	35	,	1280	,	6300		--	$US
	UNION ALL SELECT 	47	,	14800	,	74000		--	DDD
	UNION ALL SELECT 	6	,	920		,	4600		--	EURO
	UNION ALL SELECT 	12	,	760		,	3800		--	GBP
	UNION ALL SELECT 	5	,	9900	,	49000		--	HK$
	UNION ALL SELECT 	33	,	14800	,	74000		--	IDD
	UNION ALL SELECT 	15	,	14800	,	74000	--	IN
	UNION ALL SELECT 	22	,	14800	,	74000	--	IND
	UNION ALL SELECT 	40	,	1280	,	6300	--	IRR
	UNION ALL SELECT 	17	,	1280	,	6300	--	NTD
	UNION ALL SELECT 	2	,	4200	,	21000	--	RM
	UNION ALL SELECT 	13	,	7800	,	39000	--	RMB
	UNION ALL SELECT 	1	,	1600	,	8100	--	SD$
	UNION ALL SELECT 	4	,	41000	,	207000	--	TB
	UNION ALL SELECT 	43	,	41000	,	207000	--	THB
	UNION ALL SELECT 	3	,	1280	,	6300	--	US$
	UNION ALL SELECT 	45	,	1365000	,	6830000	--	Won
	UNION ALL SELECT 	16	,	1280	,	6300	--	Yen
	UNION ALL SELECT 	64	,	1280	,	6300	--	UT		
	
	UPDATE ci
	SET maxperball161 = t.maxperball
	FROM custinfo ci WITH(UPDLOCK,ROWLOCK)
		INNER JOIN @tmp_settings t ON ci.currency = t.currency
	WHERE custid IN (SELECT custid FROM @res)
		
	IF (SELECT COUNT(1)
		FROM sys.objects
		WHERE NAME IN ('custsetting3rd') AND type = 'U'
		) <> 1 RETURN 

	UPDATE cs3 WITH(UPDLOCK,ROWLOCK)
	SET cs3.maxbet = t.maxbet
	FROM custsetting3rd cs3 WITH(UPDLOCK,ROWLOCK)
		INNER JOIN custinfo ci WITH(NOLOCK) ON ci.custid = cs3.custid AND cs3.sporttype = 161
		INNER JOIN @tmp_settings t ON ci.currency = t.currency
	WHERE ci.custid IN (SELECT * FROM @res)

END
GO	



DECLARE @SummaryOfChanges TABLE(Change VARCHAR(20));

MERGE INTO LimitLoss_Setting AS Target
USING (SELECT CustID, MaxLoss FROM @tmp) AS src (CustID, MaxLoss)
ON Target.CustID = src.CustID
WHEN MATCHED THEN
UPDATE SET MaxLoss = src.MaxLoss
WHEN NOT MATCHED BY TARGET THEN
INSERT (CustID, MaxLoss) VALUES (CustID, MaxLoss)
OUTPUT $action INTO @SummaryOfChanges;

-- Query the results of the table variable.
SELECT Change, COUNT(*) AS CountPerChange
FROM @SummaryOfChanges
GROUP BY Change
